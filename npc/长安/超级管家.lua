local NPC = {}

-- ========================================================
-- ⚙️ 核心配置：在此修改重铸/置换每次需要消耗的银两数值
-- ========================================================
local 消耗银两 = 10000

-- ========================================================
-- 💡 本地内存缓存表：利用 玩家.nid 记录点击状态
-- ========================================================
local 玩家操作缓存 = {}

-- ========================================================
-- 1. NPC 静态神兵数据库配置
-- ========================================================
local _武器 = { "金箍棒", "宣花斧", "盘古锤", "枯骨刀", "乾坤无定", "芭蕉扇", "八景灯", "多情环","赤炼鬼爪", "毁天灭地", "搜魂钩", "混天绫", "索魂幡", "震天戟", "缚龙索", "斩妖剑" }
local _衣服 = { "锁子黄金甲", "五彩宝莲衣" }
local _帽子 = { "凤翅瑶仙簪", "紫金七星冠" }
local _项链 = { "混元盘金锁" }
local _鞋子 = { "藕丝步云履", "步定乾坤履" }

-- 💡 新增：全神兵大池子（把上面的所有部位融合成一个大表，方便全随机抽取）
local _全神兵集合 = {}
for _, v in ipairs(_武器) do table.insert(_全神兵集合, v) end
-- for _, v in ipairs(_衣服) do table.insert(_全神兵集合, v) end
-- for _, v in ipairs(_帽子) do table.insert(_全神兵集合, v) end
for _, v in ipairs(_项链) do table.insert(_全神兵集合, v) end
for _, v in ipairs(_鞋子) do table.insert(_全神兵集合, v) end

-- ========================================================
-- 2. NPC 主对话菜单
-- ========================================================
local 对话 = [[
这位大侠，欢迎光临！
在我这里可以进行1级神兵的各项个性化定制。
menu
1|1级神兵属性重铸（同名字随机属性）
2|1级神兵类型置换（同部位随机换类型）
5|1级神兵全随机置换（全种类无视部位乱换）
3|送我回自己的庭院
4|查询今日地煞星挑战次数
99|我只是路过看看
]]

function NPC:NPC对话(玩家, i)
    return 对话
end

-- ========================================================
-- 3. NPC 菜单分支响应
-- ========================================================
function NPC:NPC菜单(玩家, i)
    local nid = 玩家.nid

    -- ---------- 选项 1：属性重铸 ----------
    if i == "1" then
        玩家操作缓存[nid] = "属性重铸"
        玩家:打开给予窗口(self.nid) 

    -- ---------- 选项 2：类型置换 ----------
    elseif i == "2" then
        玩家操作缓存[nid] = "类型置换"
        玩家:打开给予窗口(self.nid)

    -- ---------- 选项 5：全随机置换（新增） ----------
    elseif i == "5" then
        玩家操作缓存[nid] = "全随机置换"
        玩家:打开给予窗口(self.nid)

    -- ---------- 选项 3：送我回自己的庭院 ----------
    elseif i == '3' then
        玩家:切换地图(1195, 57, 100) 
        玩家:发送系统("正在将您送回私家庭院...")

    -- ---------- 选项 4：查询今日地煞星挑战次数 ----------
    elseif i == '4' then
        local 查询报告 = "--- 今日地煞星挑战报告 ---\n"
        local 有记录 = false
        for 星级 = 1, 21 do
            local 限制Key = '地煞星_' .. tostring(星级)
            local 已杀次数 = 玩家:取活动限制次数(限制Key) or 0
            if 已杀次数 > 0 then
                查询报告 = 查询报告 .. "【" .. 星级 .. "级星】: 已挑战 " .. 已杀次数 .. " / 15 次\n"
                有记录 = true
            end
        end
        if not 有记录 then 查询报告 = 查询报告 .. "您今天还没有挑战过任何地煞星。" end
        玩家:发送系统(查询报告)
    end
end

-- ========================================================
-- 4. 辅助函数：通过当前神兵名称，判定并捞取同部位的随机新名称
-- ========================================================
local function 获取同部位随机名称(当前名称)
    for _, name in ipairs(_武器) do if name == 当前名称 then return _武器[math.random(#_武器)] end end
    for _, name in ipairs(_衣服) do if name == 当前名称 then return _衣服[math.random(#_衣服)] end end
    for _, name in ipairs(_帽子) do if name == 当前名称 then return _帽子[math.random(#_帽子)] end end
    for _, name in ipairs(_项链) do if name == 当前名称 then return _项链[math.random(#_项链)] end end
    for _, name in ipairs(_鞋子) do if name == 当前名称 then return _鞋子[math.random(#_鞋子)] end end
    return nil
end

-- ========================================================
-- 5. 核心处理：玩家放入物品并确定后的触发回调
-- ========================================================
function NPC:NPC给予(玩家, cash, items)
    if not items or not items[1] then
        return '您需要放入需要处理的物品。'
    end

    local 目标物品 = items[1]
    local nid = 玩家.nid
    local 操作类型 = 玩家操作缓存[nid]
    
    -- 取出后立刻清理缓存
    玩家操作缓存[nid] = nil

    if not 目标物品.神兵 then
        return '这不是神兵，少拿别的东西来糊弄我！#04'
    end
    
    if tonumber(目标物品.等级) ~= 1 then
        return '抱歉，我这里重铸与置换只支持【1级】神兵！#18'
    end

    local 旧神兵名称 = 目标物品.原名 or 目标物品.名称
    local 新神兵名称 = 旧神兵名称 

    -- 根据不同的操作类型，走不同的名字生成逻辑
    if 操作类型 == "类型置换" then
        local 随机名字 = 获取同部位随机名称(旧神兵名称)
        if not 随机名字 then
            return "未能识别该神兵的对应部位，无法置换类型！"
        end
        新神兵名称 = 随机名字
        
    elseif 操作类型 == "全随机置换" then
        -- 💡 核心改动：打破部位限制，直接从全池子里盲盒随机抽取
        新神兵名称 = _全神兵集合[math.random(#_全神兵集合)]
    end

    -- 动态组织确认窗口提示语
    local 提示语 = ""
    if 操作类型 == "类型置换" then
        提示语 = "您确认要消耗 #Y" .. 消耗银两 .. "两银子#W，将这件 [#R" .. 旧神兵名称 .. "#W] 随机置换为同部位的其它类型神兵吗？"
    elseif 操作类型 == "全随机置换" then
        提示语 = "您确认要消耗 #Y" .. 消耗银两 .. "两银子#W，将这件 [#R" .. 旧神兵名称 .. "#W] 进行【全种类大乱换】（部位完全随机）吗？"
    else
        提示语 = "您确认要消耗 #Y" .. 消耗银两 .. "两银子#W，将这件 [#R" .. 旧神兵名称 .. "#W] 重置随机属性吗？"
    end

    local 确认 = 玩家:确认窗口(提示语, 旧神兵名称)
    if 确认 then
        -- 内存生成新装备
        local r = 生成装备 { 名称 = 新神兵名称, 等级 = 1, 禁止交易 = 目标物品.禁止交易 }
        if not r then
            return "神兵处理失败，底层配置或内存错误！旧装备未扣除。"
        end

        -- 尝试放入背包
        if 玩家:添加物品({ r }) then
            -- 安全扣除资源
            玩家:扣除银子(消耗银两) 
            目标物品:接受(1) 
            
            if 操作类型 == "类型置换" then
                玩家操作缓存[nid] = "类型置换"
                玩家:发送系统("#G【神兵置换】置换成功！消耗 " .. 消耗银两 .. " 两银子。旧神兵[#R" .. 旧神兵名称 .. "#G]已成功置换为同部位新神兵[#Y" .. 新神兵名称 .. "#G]！")
            elseif 操作类型 == "全随机置换" then
                玩家操作缓存[nid] = "全随机置换"
                玩家:发送系统("#G【全能置换】逆天改命成功！消耗 " .. 消耗银两 .. " 两银子。旧神兵[#R" .. 旧神兵名称 .. "#G]已彻底转世为[#Y" .. 新神兵名称 .. "#G]！")
            else
                玩家操作缓存[nid] = "属性重铸"
                玩家:发送系统("#G【神兵重铸】重铸成功！消耗 " .. 消耗银两 .. " 两银子。已重塑[#R" .. 旧神兵名称 .. "#G]的初值属性！")
            end
            玩家:打开给予窗口(self.nid)
            return
        else
            -- 背包满了，安全退回
            return "您的包裹已满，无法接收新神兵！操作已取消，旧装备未扣除。"
        end
    end
end

return NPC