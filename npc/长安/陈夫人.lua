    return 对话
end

-- ========================================================
-- 3. NPC 菜单分支响应
-- ========================================================
function NPC:NPC菜单(玩家, i)
    if i == "1" then
        玩家:打开给予窗口(self.nid) 
    end
end

-- ========================================================
-- 4. 核心处理：静默回收发放
-- ========================================================
function NPC:NPC给予(玩家, cash, items)
    if not items or not items[1] then
        return
    end

    local 目标物品 = items[1]
    local 配饰名称 = 目标物品.原名 or 目标物品.名称

    -- 严格验证是否为指定配饰
    if 有效配饰表[配饰名称] then
        -- 生成奖励
        local r = 生成物品 { 名称 = 目标道具名称, 数量 = 奖励数量 }
        if r then
            -- 尝试发放
            if 玩家:添加物品({ r }) then
                -- 扣除并销毁配饰
                目标物品:接受(1) 
				玩家:打开给予窗口(self.nid)
            end
        end
    end
end

return NPC
